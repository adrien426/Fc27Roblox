// Writes src/shared/PlayerRest.luau: the rest pose of the player model's bones as they are in player.glb
// (local rotation of each bone, and the hips height above the feet). src/shared/Skeleton.luau needs it because
// the clips hold the bones' local rotations as three.js sets them in the web game: on Roblox each bone is
// turned by Transform = (rest in player.glb)⁻¹ · (clip), whatever frames Roblox's importer gave the bones.
// Usage: node build-rest.mjs
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import draco3d from 'draco3dgltf';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const io = new NodeIO()
  .registerExtensions(ALL_EXTENSIONS)
  .registerDependencies({ 'draco3d.decoder': await draco3d.createDecoderModule() });
const doc = await io.read(join(ROOT, 'assets', 'source', 'player.glb'));
const key = name => name.replace(/^mixamorig\d*[:_.]?/, '');

const rot = {};
let hipsY = 0;
for (const skin of doc.getRoot().listSkins()) {
  for (const j of skin.listJoints()) {
    const k = key(j.getName());
    if (rot[k]) continue;
    rot[k] = j.getRotation();
    if (k === 'Hips') hipsY = j.getWorldTranslation()[1];
  }
}

// Model height (bind pose), to turn the hips height into a fraction of it
let minY = Infinity, maxY = -Infinity;
for (const mesh of doc.getRoot().listMeshes()) {
  for (const prim of mesh.listPrimitives()) {
    const a = prim.getAttribute('POSITION');
    minY = Math.min(minY, a.getMin([])[1]);
    maxY = Math.max(maxY, a.getMax([])[1]);
  }
}

const f = v => Number(v.toFixed(6));
const lines = Object.keys(rot).sort().map(k => {
  const [x, y, z, w] = rot[k];
  return `\t\t${k} = { ${f(x)}, ${f(y)}, ${f(z)}, ${f(w)} },`;
});
writeFileSync(join(ROOT, 'src', 'shared', 'PlayerRest.luau'), `-- Generated by scripts/build-rest.mjs from assets/source/player.glb. Do not edit by hand.
-- rot: local rotation (quaternion x, y, z, w) of each bone in the rest pose; hipsHeight: hips above the feet,
-- as a fraction of the model's height.
return {
\thipsHeight = ${f((hipsY - minY) / (maxY - minY))},
\trot = {
${lines.join('\n')}
\t},
}
`);
console.log(`PlayerRest.luau: ${lines.length} bones, hips at ${((hipsY - minY) / (maxY - minY) * 100).toFixed(1)} % of the height`);
