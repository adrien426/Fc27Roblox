// Converts the web game's Mixamo clips (assets/source/anims/*.json, three.js format) into Luau modules
// (src/shared/Clips/<name>.luau) that src/shared/Skeleton.luau plays on the bones of the player model.
// - base.json: the clips embedded in the web game (idle, run, kick, dives...), extracted by extract-web-clips.mjs
// - clips.json: the extra clips (walk, getUp, victory, dance...), siuu.json: the celebration
// Each clip keeps the 22 body bones (no fingers), resampled at 30 frames per second. Rotations are the bones'
// local quaternions, stored as int16 and base64. The hips height is stored as a ratio of the model's rest height
// (the web game keeps the body in place the same way: the game moves the player, the clip only bends him).
// Usage: node build-anims.mjs
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, '..', 'assets', 'source', 'anims');
const OUT = join(HERE, '..', 'src', 'shared', 'Clips');
const FPS = 30;
const BONES = ['Hips', 'Spine', 'Spine1', 'Spine2', 'Neck', 'Head',
  'LeftShoulder', 'LeftArm', 'LeftForeArm', 'LeftHand', 'RightShoulder', 'RightArm', 'RightForeArm', 'RightHand',
  'LeftUpLeg', 'LeftLeg', 'LeftFoot', 'LeftToeBase', 'RightUpLeg', 'RightLeg', 'RightFoot', 'RightToeBase'];
// Looping clips, as in the web game (the others play once and hold their last frame)
const LOOP = new Set(['idle', 'idleN', 'jog', 'run', 'back', 'strL', 'strR', 'gkIdle', 'fallen', 'win', 'walk', 'gkSide', 'gkSideR', 'dance', 'clap']);

const bone = name => name.replace(/^mixamorig\d*:?/, '').replace(/\.(quaternion|position)$/, '');

function sampler(track, size) {
  const t = track.times, v = track.values;
  return time => {
    if (time <= t[0]) return v.slice(0, size);
    const n = t.length;
    if (time >= t[n - 1]) return v.slice((n - 1) * size, n * size);
    let i = 1;
    while (t[i] < time) i++;
    const k = (time - t[i - 1]) / (t[i] - t[i - 1]), a = (i - 1) * size, b = i * size, out = [];
    let dot = 0;
    if (size === 4) for (let c = 0; c < 4; c++) dot += v[a + c] * v[b + c];
    const sgn = dot < 0 ? -1 : 1;
    for (let c = 0; c < size; c++) out.push(v[a + c] + (sgn * v[b + c] - v[a + c]) * k);
    if (size === 4) { const l = Math.hypot(...out) || 1; for (let c = 0; c < 4; c++) out[c] /= l; }
    return out;
  };
}

// Left/right swapped copy (the keeper side-step only exists towards the left, like in the web game)
function mirror(clip, name) {
  const m = JSON.parse(JSON.stringify(clip));
  m.name = name;
  for (const t of m.tracks) {
    t.name = t.name.replace(/Left|Right/, s => (s === 'Left' ? 'Right' : 'Left'));
    const v = t.values;
    if (/\.quaternion$/.test(t.name)) for (let i = 0; i < v.length; i += 4) { v[i + 1] = -v[i + 1]; v[i + 2] = -v[i + 2]; }
    else if (/\.position$/.test(t.name)) for (let i = 0; i < v.length; i += 3) v[i] = -v[i];
  }
  return m;
}

function encode(name, clip, hipsRef) {
  const dur = clip.duration;
  const frames = Math.max(2, Math.round(dur * FPS) + 1);
  const byBone = {};
  let hips = null;
  for (const t of clip.tracks) {
    const b = bone(t.name);
    if (/\.quaternion$/.test(t.name) && BONES.includes(b)) byBone[b] = sampler(t, 4);
    if (/\.position$/.test(t.name) && b === 'Hips') hips = sampler(t, 3);
  }
  const lines = [];
  for (const b of BONES) {
    const s = byBone[b];
    if (!s) continue;
    const buf = Buffer.alloc(frames * 8);
    let prev = null;
    for (let f = 0; f < frames; f++) {
      let q = s(Math.min(dur, f / FPS));
      // Same hemisphere as the previous frame, so the runtime can blend frames directly
      if (prev && q[0] * prev[0] + q[1] * prev[1] + q[2] * prev[2] + q[3] * prev[3] < 0) q = q.map(x => -x);
      prev = q;
      for (let c = 0; c < 4; c++) buf.writeInt16LE(Math.round(Math.max(-1, Math.min(1, q[c])) * 32767), f * 8 + c * 2);
    }
    lines.push(`\t\t${b} = "${buf.toString('base64')}",`);
  }
  let hy = '';
  if (hips) {
    const buf = Buffer.alloc(frames * 2);
    for (let f = 0; f < frames; f++) buf.writeInt16LE(Math.round((hips(Math.min(dur, f / FPS))[1] / hipsRef) * 10000), f * 2);
    hy = `\thy = "${buf.toString('base64')}",\n`;
  }
  return `-- Generated by scripts/build-anims.mjs from the web game's "${name}" clip. Do not edit by hand.
-- frames: rotation of each bone (x, y, z, w as int16, base64) at ${FPS} frames per second; hy: hips height / rest height (x 10000)
return {
\tduration = ${+dur.toFixed(4)},
\tframes = ${frames},
\tloop = ${LOOP.has(name)},
${hy}\tbones = {
${lines.join('\n')}
\t},
}
`;
}

const base = JSON.parse(readFileSync(join(SRC, 'base.json'), 'utf8'));
const extra = JSON.parse(readFileSync(join(SRC, 'clips.json'), 'utf8'));
const siuu = JSON.parse(readFileSync(join(SRC, 'siuu.json'), 'utf8'));
// Hips rest height of each source rig: 0.93 m for the X Bot clips, 0.928 m for the Ch38 celebration
const all = [];
for (const [k, c] of Object.entries(base)) all.push([k, c, 0.93]);
for (const [k, c] of Object.entries(extra)) all.push([k, c, 0.93]);
all.push(['gkSideR', mirror(extra.gkSide, 'gkSideR'), 0.93]);
all.push(['siuu', siuu, 0.928]);

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
let total = 0;
for (const [k, c, ref] of all) {
  const src = encode(k, c, ref);
  writeFileSync(join(OUT, `${k}.luau`), src);
  total += src.length;
}
console.log(`${all.length} clips, ${(total / 1024).toFixed(0)} KB of Luau in src/shared/Clips`);
